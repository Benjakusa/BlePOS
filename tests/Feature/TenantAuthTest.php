<?php

namespace Tests\Feature;

use App\Models\Tenant;
use App\Models\User;
use Database\Seeders\HotelTenantSeeder;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Tests\TestCase;

class TenantAuthTest extends TestCase
{
    use RefreshDatabase;

    protected function setUp(): void
    {
        parent::setUp();
        $this->seed(HotelTenantSeeder::class);
    }

    public function test_tenant_login_screen_can_be_rendered(): void
    {
        $response = $this->get(route('tenant.login'));

        $response->assertStatus(200);
        $response->assertSee('Welcome');
        $response->assertSee('Sign in to your business workspace');
    }

    public function test_tenant_user_can_authenticate_and_access_dashboard(): void
    {
        $response = $this->post(route('tenant.login.store'), [
            'email' => 'hotel.owner@blepos.co.ke',
            'password' => 'Hotel@123456!',
        ]);

        $this->assertAuthenticated('web');
        $response->assertRedirect(route('tenant.dashboard'));

        $dashboardResponse = $this->get(route('tenant.dashboard'));
        $dashboardResponse->assertRedirect(route('tenant.mfa.setup'));
        $this->get(route('tenant.mfa.setup'))
            ->assertOk()
            ->assertSee('Set up two-factor authentication');
    }

    public function test_tenant_user_cannot_authenticate_with_invalid_password(): void
    {
        $response = $this->post(route('tenant.login.store'), [
            'email' => 'hotel.owner@blepos.co.ke',
            'password' => 'wrong-password',
        ]);

        $this->assertGuest('web');
        $response->assertSessionHasErrors('email');
    }

    public function test_suspended_tenant_user_cannot_login(): void
    {
        $tenant = Tenant::where('slug', 'grand-horizon-hotel')->first();
        $tenant->update(['status' => 'suspended']);

        $response = $this->post(route('tenant.login.store'), [
            'email' => 'hotel.owner@blepos.co.ke',
            'password' => 'Hotel@123456!',
        ]);

        $this->assertGuest('web');
        $response->assertSessionHasErrors('email');
    }

    public function test_tenant_user_can_logout(): void
    {
        $user = User::where('email', 'hotel.owner@blepos.co.ke')->first();

        $response = $this->actingAs($user, 'web')->post(route('tenant.logout'));

        $this->assertGuest('web');
        $response->assertRedirect(route('tenant.login'));
    }

    public function test_unauthenticated_request_to_tenant_area_redirects_to_tenant_login(): void
    {
        $response = $this->get(route('tenant.dashboard'));

        $response->assertRedirect(route('tenant.login'));
    }

    public function test_tenant_code_is_autogenerated_as_6_digit_number(): void
    {
        $code = Tenant::generateUniqueCode();

        $this->assertMatchesRegularExpression('/^\d{6}$/', $code);
    }
}
